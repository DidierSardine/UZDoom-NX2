# literals that are data/keys in some files: only translate them in the UI files
UI_ONLY = {"RDoom", "Perfil", "Nome", "Tipo", "Estado", "Jogo", "Valor", "Erro", "Arquivo", "Formato", "Categoria",
           "Baixa", "Alta", "Nenhum", "RDoom — Stock Switch"}


def main():
    total = 0
    for rel in FILES:
        path = os.path.join(ROOT, rel)
        s = open(path, encoding="utf-8").read()
        n0 = 0
        # longest first, so a literal is never replaced by a shorter key's rule
        for pt in sorted(T, key=len, reverse=True):
            if pt in UI_ONLY and "/ui/" not in rel:
                continue
            lit = '"' + pt + '"'
            c = s.count(lit)
            if c:
                s = s.replace(lit, '"' + T[pt] + '"')
                n0 += c
        open(path, "w", encoding="utf-8").write(s)
        print("%s: %d literal(s)" % (rel, n0))
        total += n0
    print("total: %d" % total)


if __name__ == "__main__":
    sys.exit(main())
